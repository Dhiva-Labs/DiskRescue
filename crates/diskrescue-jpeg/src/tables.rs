/// Length of the segment returned by [`standard_dht`] (marker included).
pub const STANDARD_DHT_LEN: usize = 420;

/// Natural (row-major) index of the k-th coefficient in zigzag order.
pub const ZIGZAG: [u8; 64] = [
    0, 1, 8, 16, 9, 2, 3, 10, 17, 24, 32, 25, 18, 11, 4, 5, 12, 19, 26, 33, 40, 48, 41, 34, 27, 20,
    13, 6, 7, 14, 21, 28, 35, 42, 49, 56, 57, 50, 43, 36, 29, 22, 15, 23, 30, 37, 44, 51, 58, 59,
    52, 45, 38, 31, 39, 46, 53, 60, 61, 54, 47, 55, 62, 63,
];

/// The four Annex K tables encoded as a single DHT segment, marker
/// included: `FF C4 01 A2`, then DC luminance (00), AC luminance (10),
/// DC chrominance (01) and AC chrominance (11).
pub fn standard_dht() -> Vec<u8> {
    let mut v = Vec::with_capacity(STANDARD_DHT_LEN);
    v.extend_from_slice(&[0xFF, 0xC4]);
    let len = (STANDARD_DHT_LEN - 2) as u16;
    v.extend_from_slice(&len.to_be_bytes());
    let parts: [(u8, &[u8; 16], &[u8]); 4] = [
        (0x00, &DC_LUMINANCE_BITS, &DC_LUMINANCE_VALUES),
        (0x10, &AC_LUMINANCE_BITS, &AC_LUMINANCE_VALUES),
        (0x01, &DC_CHROMINANCE_BITS, &DC_CHROMINANCE_VALUES),
        (0x11, &AC_CHROMINANCE_BITS, &AC_CHROMINANCE_VALUES),
    ];
    for (tc_th, bits, vals) in parts {
        v.push(tc_th);
        v.extend_from_slice(bits);
        v.extend_from_slice(vals);
    }
    v
}

/// The standard table for `class` (0 = DC, 1 = AC) and `id` (0 =
/// luminance, 1 = chrominance), or `None` for other ids.
pub fn standard_table(class: u8, id: u8) -> Option<HuffmanTable> {
    let (bits, values): (&[u8; 16], &[u8]) = match (class, id) {
        (0, 0) => (&DC_LUMINANCE_BITS, &DC_LUMINANCE_VALUES),
        (0, 1) => (&DC_CHROMINANCE_BITS, &DC_CHROMINANCE_VALUES),
        (1, 0) => (&AC_LUMINANCE_BITS, &AC_LUMINANCE_VALUES),
        (1, 1) => (&AC_CHROMINANCE_BITS, &AC_CHROMINANCE_VALUES),
        _ => return None,
    };
    Some(HuffmanTable {
        class,
        id,
        bits: *bits,
        values: values.to_vec(),
        offset: 0,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn standard_dht_layout() {
        let d = standard_dht();
        assert_eq!(d.len(), STANDARD_DHT_LEN);
        assert_eq!(&d[..4], &[0xFF, 0xC4, 0x01, 0xA2]);
        assert_eq!(d[4], 0x00);
        assert_eq!(d[4 + 17 + 12], 0x10);
        let sum = |b: &[u8; 16]| b.iter().map(|&x| x as usize).sum::<usize>();
        assert_eq!(sum(&DC_LUMINANCE_BITS), 12);
        assert_eq!(sum(&DC_CHROMINANCE_BITS), 12);
        assert_eq!(sum(&AC_LUMINANCE_BITS), 162);
        assert_eq!(sum(&AC_CHROMINANCE_BITS), 162);
    }

    #[test]
    fn zigzag_is_a_permutation() {
        let mut seen = [false; 64];
        for &z in &ZIGZAG {
            assert!(!seen[z as usize]);
            seen[z as usize] = true;
        }
    }

    #[test]
    fn standard_tables_by_id() {
        assert!(standard_table(0, 0).is_some());
        assert!(standard_table(1, 1).is_some());
        assert!(standard_table(0, 2).is_none());
        assert!(standard_table(1, 0).unwrap().is_standard());
    }
}
